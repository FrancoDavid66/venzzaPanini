const pad = (n) => String(n).padStart(2, '0');
const partir = (v) => {
  const [H, M = 0] = String(v).split(':').map(Number);
  return [H, M];
};

// ---------- Formatos de hora por idioma ----------
const horaES = (v) => {
  const [H, M] = partir(v);
  return M ? `${H}:${pad(M)} hs` : `${H} hs`;
};
const horaIT = (v) => {
  const [H, M] = partir(v);
  return M ? `${H}:${pad(M)}` : `${H}`;
};
const horaEN = (v) => {
  const [H, M] = partir(v);
  const suf = H >= 12 && H < 24 ? 'pm' : 'am';
  const hh = H % 12 || 12;
  return M ? `${hh}:${pad(M)} ${suf}` : `${hh} ${suf}`;
};
const rangoEN = (d, h) => {
  const a = horaEN(d);
  const b = horaEN(h);
  const [na, sa] = a.split(' ');
  const [, sb] = b.split(' ');
  return sa === sb ? `${na}–${b}` : `${a}–${b}`;
};

